# ============================================================
#  🧠 سیستم چرخش (Anti-Repetition Memory)
# ============================================================

# استفاده از deque برای اینکه بتونیم تعداد مشخصی از آیتم‌های اخیر رو به خاطر بسپاریم.
# وقتی ظرفیت (maxlen) پر بشه، قدیمی‌ترین آیتم خودش حذف می‌شه.
_tip_history = deque(maxlen=25)   # ۲۵ نکته آخر رو به خاطر بسپار
_fact_history = deque(maxlen=25)  # ۲۵ فکت آخر رو به خاطر بسپار
_myth_history = deque(maxlen=10)  # ۱۰ باور غلط آخر رو به خاطر بسپار


def get_tip() -> str:
    """انتخاب یک نکته جدید که در ۲۵ مورد اخیر استفاده نشده باشد."""
    available = [t for t in TIPS if t not in _tip_history]
    if not available:
        # اگر همه نکات استفاده شده بودند، حافظه رو ریست می‌کنیم
        _tip_history.clear()
        available = TIPS
    
    chosen = random.choice(available)
    _tip_history.append(chosen)
    return chosen


def get_fact() -> str:
    """انتخاب یک فکت جدید که در ۲۵ مورد اخیر استفاده نشده باشد."""
    available = [f for f in FACTS if f not in _fact_history]
    if not available:
        _fact_history.clear()
        available = FACTS
        
    chosen = random.choice(available)
    _fact_history.append(chosen)
    return chosen


def get_myth() -> tuple[str, str]:
    """انتخاب یک باور غلط جدید که در ۱۰ مورد اخیر استفاده نشده باشد."""
    available = [m for m in MYTHS if m not in _myth_history]
    if not available:
        _myth_history.clear()
        available = MYTHS
        
    chosen = random.choice(available)
    _myth_history.append(chosen)
    return chosen
