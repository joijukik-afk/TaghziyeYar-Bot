# ============================================================
#  🧠 سیستم چرخش (Anti-Repetition Memory)
# ============================================================

_tip_history = deque(maxlen=25)
_fact_history = deque(maxlen=25)
_myth_history = deque(maxlen=10)

# 👈 قفل برای آینده (اگر از Thread استفاده شد)
_content_lock = Lock()


def _pick_next(items: list, history: deque) -> any:
    """
    انتخاب هوشمند آیتم بعدی:
    1. اولویت با آیتم‌های دیده‌نشده
    2. در صورت پر شدن حافظه، آیتم قبلی حذف می‌شود تا تکراری فوری رخ نده
    """
    available = [t for t in items if t not in history]
    if not available:
        last = history[-1] if history else None
        history.clear()
        available = [t for t in items if t != last] or items

    chosen = random.choice(available)
    history.append(chosen)
    return chosen


def get_tip() -> str:
    with _content_lock:
        return _pick_next(TIPS, _tip_history)


def get_fact() -> str:
    with _content_lock:
        return _pick_next(FACTS, _fact_history)


def get_myth() -> tuple[str, str]:
    with _content_lock:
        return _pick_next(MYTHS, _myth_history)


def reset_history() -> None:
    with _content_lock:
        _tip_history.clear()
        _fact_history.clear()
        _myth_history.clear()
        logger.info("Content history reset by admin")


def _validate_content():
    for i, tip in enumerate(TIPS):
        if not tip or not tip.strip():
            logger.error(f"TIPS[{i}] is empty!")
    for i, fact in enumerate(FACTS):
        if not fact or not fact.strip():
            logger.error(f"FACTS[{i}] is empty!")
    for i, myth in enumerate(MYTHS):
        if not isinstance(myth, tuple) or len(myth) != 2:
            logger.error(f"MYTHS[{i}] is malformed!")
        elif not myth[0] or not myth[1]:
            logger.error(f"MYTHS[{i}] has empty element!")


_validate_content()
